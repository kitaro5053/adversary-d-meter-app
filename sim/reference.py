def role_placement_summary(set_name: str) -> dict[str, str]:
    """役職 → 『どのルールで何人配置されるか』の要約（例: 殺人計画×1／友情サークル×2）。"""
    from collections import Counter

    from .state import BTX_RULE_X_ROLES, BTX_RULE_Y_ROLES, FS_RULE_X_ROLES, FS_RULE_Y_ROLES
    if set_name == "FS":
        tables = [("Y", FS_RULE_Y_ROLES), ("X", FS_RULE_X_ROLES)]
    else:
        tables = [("Y", BTX_RULE_Y_ROLES), ("X", BTX_RULE_X_ROLES)]
    out: dict[str, list[str]] = {}
    for _kind, tbl in tables:
        for rule, roles in tbl.items():
            for role, n in Counter(roles).items():
                label = f"{rule}×{n}" if n > 1 else rule
                if role == "マイナス":
                    label = f"{rule}×0〜{n}"
                out.setdefault(role, []).append(label)
    return {r: "／".join(v) for r, v in out.items()}


