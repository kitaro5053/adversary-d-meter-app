def get_tutorial(key: str) -> Tutorial:
    t = next((t for t in TUTORIALS if t.key == key), None)
    if t is None:
        raise KeyError(f"未知のチュートリアル: {key}")
    return t


def format_tutorial_intro(t: Tutorial) -> list[str]:
    """開始前に表示する教材テキスト（Markdown行）。"""
    lines = [f"## {t.title}", t.summary, "", "**この脚本で学ぶこと:**"]
    lines += [f"- {x}" for x in t.learn]
    lines += ["", "**プレイ中の注目ポイント:**"]
    lines += [f"- {x}" for x in t.watch]
    if t.after:
        lines += ["", f"**終わったら:** {t.after}"]
    return lines
