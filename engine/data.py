def ability_class_target_alive(user: str, ability: str, alive_names) -> bool:
    """★A-23/B-24 共通ヘルパ：対象クラスが限定された友好能力に、生存する対象が居るか（FI-2）。

    現状のクラス限定は「学生」系のみ（教師『学生の役職開示/学生の不安操作』＝同エリアの学生／
    男子学生・女子学生『学生の不安除去』＝**他の**学生）。対象クラスに生存者が居なければ能力は
    空撃ち＝脚本家には脅威でなく（A-23＝友好禁止の無駄手）、主人公には投資先でない（B-24＝phantom）。
    クラス限定でない能力は True（この判定の対象外）。エリア一致は要求しない（移動で合流しうる＝健全側）。
    ★学生判定は STUDENTS を単一ソース＝sim.reference の CHARACTER_ATTRIBUTES『学生』と等価
    （tests/test_target_existence.py が等価を固定）。alive_names＝生存キャラ名の列/集合。
    """
    if "学生" not in ability:
        return True
    return any(n != user and is_student(n) for n in alive_names)


