    """(キャラ, 能力名) の投資ジャンルタグ（kind）を返す。未収録は None（範囲外/要確認）。

    ★単一ソース＝投資評価の減衰カーブ選択はここだけを引く（FI-1）。空リストのキャラ（能力なし）や
    範囲外キャラは None。kind は必ず ABILITY_KIND_SET に含まれる（tests が固定）。
    """
    return ABILITY_KINDS.get((character_name, ability_name))


