def script_possible(node_id: str, *, roles: set[str], incidents: set[str],
                    rule_y: str, rule_x: set[str]) -> bool:
    """脚本開始時に確定する gate 判定（DP-1 の script_impossible 用・Stage 2で本接続）。"""
    node = LOSS_NODES.get(node_id)
    if node is None:
        return True
    g = node.get("gate", {})
    if "roles" in g and not all(r in roles for r in g["roles"]):
        return False
    if "roles_any" in g or "or_rule_x" in g:
        any_role = any(r in roles for r in g.get("roles_any", []))
        any_rule = any(r in rule_x for r in g.get("or_rule_x", []))
        if not (any_role or any_rule):
            return False
    if "roles_vip" in g and not any(r in roles for r in g["roles_vip"]):
        return False
    if "incidents" in g and not all(i in incidents for i in g["incidents"]):
        return False
    if "incidents_any" in g and not any(i in incidents for i in g["incidents_any"]):
        return False
    if "rule_y" in g and rule_y not in g["rule_y"]:
        return False
    if "rule_x" in g and not any(r in rule_x for r in g["rule_x"]):
        return False
    return True


def to_mermaid(node_ids: list[str] | None = None, statuses: dict[str, str] | None = None) -> str:
    """負け筋ネットワークを mermaid flowchart に描く
    （statuses: id→'gray'|'active'|'covered'|'dormant'）。

    ★A-45：許可クラスは**ホワイトリスト**＝未知の値は 'loss'（赤）に落ちる。B-39 で dormant を
    足した時、ここへ追記しないと『まだ立っていない負け筋が真っ赤に描かれる』＝実害のある
    見え方になる（classDef を足すだけでは効かない＝適用側もホワイトリスト）。
    """
    ids = node_ids if node_ids is not None else list(LOSS_NODES)
    statuses = statuses or {}
    out = ["flowchart TD"]
    out.append('  LOSE["🟥 このループで敗北"]:::loss')
    _ALLOWED = {"gray": "gray", "covered": "covered", "dormant": "dormant"}
    for nid in ids:
        n = LOSS_NODES[nid]
        cls = _ALLOWED.get(statuses.get(nid, ""), "loss")
        safe = nid.replace(".", "_")
        out.append(f'  LOSE --> {safe}["{n["label"]}〔{n["difficulty"]}〕"]:::{cls}')
        for c in n["conds"]:
            cid = f'{safe}_{c["id"]}'
            out.append(f'  {safe} --> {cid}(["{c["label"]}"]):::orc')
            for i, d in enumerate(c["defenses"]):
                out.append(f'  {cid} --> {cid}_d{i}["🛡 {d["label"]}（{d["prognosis"]}）"]:::def')
            for ref in c.get("refs", []):
                out.append(f'  {cid} --> {ref}[/"共有：{ref}"/]:::orc')
    out += [
        "  classDef loss fill:#c0392b,color:#fff,stroke:#7b241c;",
        "  classDef orc fill:#5dade2,color:#000,stroke:#21618c;",
        "  classDef def fill:#27ae60,color:#fff,stroke:#145a32;",
        "  classDef gray fill:#909497,color:#fff,stroke:#454b4d;",
        "  classDef covered fill:#145a32,color:#fff,stroke:#0b3d22;",
        # ★A-45（色の決定＝AIA委任・2026-07-20）：dormant（未活性）は gray と**別クラス**。
        #   リスト表示は ⚪ で区別しているのに図だけ gray に潰れると「もう起きない（ゼロ）」と
        #   同じ見え方になり、B-39 の区別（まだ立っていない＝これから立ちうる）が消える。
        #   淡色＋濃い文字＝「生きているが未発火」＝ゼロの濃灰とも covered の緑とも非衝突。
        "  classDef dormant fill:#e5e8e8,color:#212f3c,stroke:#909497,stroke-dasharray:4 3;",
    ]
    return "\n".join(out)
